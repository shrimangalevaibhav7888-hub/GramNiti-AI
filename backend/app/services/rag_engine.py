    @staticmethod
    def detect_language(text: str) -> str:
        if not text:
            return "en"
        
        # 1. Urdu (Perso-Arabic script)
        if re.search(r"[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]", text):
            return "ur"
        # 2. Gurmukhi / Punjabi
        if re.search(r"[\u0A00-\u0A7F]", text):
            return "pa"
        # 3. Gujarati
        if re.search(r"[\u0A80-\u0AFF]", text):
            return "gu"
        # 4. Tamil
        if re.search(r"[\u0B80-\u0BFF]", text):
            return "ta"
        # 5. Telugu
        if re.search(r"[\u0C00-\u0C7F]", text):
            return "te"
        # 6. Kannada
        if re.search(r"[\u0C80-\u0CFF]", text):
            return "kn"
        # 7. Malayalam
        if re.search(r"[\u0D00-\u0D7F]", text):
            return "ml"
        # 8. Odia
        if re.search(r"[\u0B00-\u0B7F]", text):
            return "or"
        # 9. Bengali / Assamese
        if re.search(r"[\u0980-\u09FF]", text):
            if bool(re.search(r"[ৰৱ]", text)) or "আছে" in text or "কৰক" in text or "নমস্কাৰ" in text:
                return "as"
            return "bn"
        # 10. Devanagari (Marathi vs Hindi)
        if re.search(r"[\u0900-\u097F]", text):
            marathi_markers = ["आहे", "नाही", "कसा", "कशी", "करावे", "योजना", "व्यवसाय", "माहिती", "पाहिजे", "शक्य", "मिळेल", "करावा", "सांगा"]
            hindi_markers = ["है", "नहीं", "कैसे", "करना", "चाहिए", "मिलेगा", "सकता", "बताइए", "योजनाएं", "बताएं"]
            mr_count = sum(1 for m in marathi_markers if m in text)
            hi_count = sum(1 for h in hindi_markers if h in text)
            if mr_count > hi_count:
                return "mr"
            return "hi"

        return "en"

